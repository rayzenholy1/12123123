import numpy as np

print("Завдання 1")
a = np.random.randint(0, 101, 10)
print("Масив до сортування:", a)
print("Мінімум:", np.min(a))
print("Максимум:", np.max(a))
print("Середнє:", np.mean(a))
b = np.sort(a)
print("Масив після сортування:", b)

print("\nЗавдання 2")
m = np.random.randint(1, 51, (4, 4))
for row in m:
    print(" ".join(f"{x:3d}" for x in row))
print("Суми за рядками:", m.sum(axis=1))
print("Суми за стовпцями:", m.sum(axis=0))
print("Загальне середнє:", m.mean())

print("\nЗавдання 3")
x = np.arange(15).reshape(3, 5)
print("Вихідний масив:")
print(x)
t = x.T
print("Транспонований масив:")
print(t)
r = x.reshape(5, 3)
print("Масив 5x3 після reshape:")
print(r)

print("\nЗавдання 4")
f = np.random.rand(10, 10)
mn = f.min()
mx = f.max()
i_mn = np.unravel_index(np.argmin(f), f.shape)
i_mx = np.unravel_index(np.argmax(f), f.shape)
print(f)
print("Мінімум:", mn, "індекс:", i_mn)
print("Максимум:", mx, "індекс:", i_mx)

print("\nЗавдання 5")
z = np.random.randint(-10, 11, 15)
print("Масив:", z)
print("Додатні елементи:", z[z > 0])
print("Парні елементи:", z[z % 2 == 0])

print("\nЗавдання 6")
